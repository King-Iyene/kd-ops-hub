// Bakes Supabase connection config into a generated TS module at build time,
// so a packaged installer (no .env sitting next to it) still knows which
// Supabase project to talk to. Same approach the web app uses via Vite's
// `import.meta.env` — the anon key is a public, RLS-gated key, safe to ship
// inside a distributed client, same as it's safe inside the web bundle.
//
// Precedence: real env vars (set by CI from repo variables, or by a local
// `.env` via dotenv during `npm start`) win. The URL has a safe baked-in
// default (same project as the rest of KD Ops Hub — its ref is already
// public in supabase/config.toml). The anon key has NO default: if it's
// never supplied, the generated config ships an empty string and the app
// shows a friendly "not configured" screen instead of crashing.
const fs = require('fs');
const path = require('path');

const DEFAULT_SUPABASE_URL = 'https://mseeurrvdcfxdmvqjjki.supabase.co';

const url = process.env.SUPABASE_URL?.trim() || DEFAULT_SUPABASE_URL;
const anonKey = process.env.SUPABASE_ANON_KEY?.trim() || '';

const out = `// AUTO-GENERATED by scripts/write-config.js at build time. Do not edit by
// hand and do not commit a version of this file with a real anon key — it's
// gitignored. See .env.example / README.md for how to supply these values.
export const SUPABASE_URL = ${JSON.stringify(url)};
export const SUPABASE_ANON_KEY = ${JSON.stringify(anonKey)};
`;

fs.writeFileSync(path.join(__dirname, '..', 'src', 'generated-config.ts'), out);
console.log(`[write-config] wrote src/generated-config.ts (anon key ${anonKey ? 'present' : 'MISSING — app will show "not configured"'})`);
